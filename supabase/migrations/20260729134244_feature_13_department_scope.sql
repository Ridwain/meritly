create function public.audit_profile_department_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  context_request_id uuid;
  context_reason text;
begin
  if new.department_id is not distinct from old.department_id then
    return new;
  end if;

  context_request_id := coalesce(
    nullif(current_setting('meritly.department_request_id', true), '')::uuid,
    gen_random_uuid()
  );
  context_reason := coalesce(
    nullif(current_setting('meritly.department_reason', true), ''),
    'Direct department change'
  );

  insert into public.user_department_history (
    request_id,
    target_user_id,
    actor_id,
    from_department_id,
    to_department_id,
    reason
  ) values (
    context_request_id,
    new.id,
    auth.uid(),
    old.department_id,
    new.department_id,
    context_reason
  );

  return new;
end;
$$;

create trigger audit_profile_department_change
after update of department_id on public.profiles
for each row execute function public.audit_profile_department_change();

revoke execute on function public.audit_profile_department_change()
  from anon, authenticated, public;

create function public.move_user_department(
  p_request_id uuid,
  p_target_user_id uuid,
  p_new_department_id integer,
  p_reason text
)
returns table (
  from_department_id integer,
  to_department_id integer,
  duplicate_request boolean
)
language plpgsql
volatile
security invoker
set search_path = ''
as $$
declare
  clean_reason text := btrim(coalesce(p_reason, ''));
  caller_id uuid := auth.uid();
  current_department_id integer;
  existing_event public.user_department_history%rowtype;
begin
  if caller_id is null
     or not public.is_active()
     or not public.has_permission('user.manage_all') then
    raise exception 'user.manage_all is required to move departments';
  end if;

  if p_request_id is null then
    raise exception 'request id is required';
  end if;
  if p_target_user_id is null or p_target_user_id = caller_id then
    raise exception 'a different target user is required';
  end if;
  if char_length(clean_reason) not between 3 and 500 then
    raise exception 'reason must be between 3 and 500 characters';
  end if;

  select h.*
  into existing_event
  from public.user_department_history h
  where h.request_id = p_request_id
    and h.actor_id = caller_id;

  if found then
    return query
      select
        existing_event.from_department_id,
        existing_event.to_department_id,
        true;
    return;
  end if;

  if not exists (
    select 1 from public.departments d where d.id = p_new_department_id
  ) then
    raise exception 'destination department not found';
  end if;

  select p.department_id
  into current_department_id
  from public.profiles p
  where p.id = p_target_user_id
  for update;

  if not found then
    raise exception 'target user not found';
  end if;
  if current_department_id = p_new_department_id then
    raise exception 'target user is already in this department';
  end if;

  perform set_config(
    'meritly.department_request_id',
    p_request_id::text,
    true
  );
  perform set_config('meritly.department_reason', clean_reason, true);

  update public.profiles
  set department_id = p_new_department_id
  where id = p_target_user_id;

  select h.*
  into existing_event
  from public.user_department_history h
  where h.request_id = p_request_id;

  if not found then
    raise exception 'department audit event was not created';
  end if;

  return query
    select
      existing_event.from_department_id,
      existing_event.to_department_id,
      false;
end;
$$;

revoke execute on function public.move_user_department(
  uuid, uuid, integer, text
) from anon, public;
grant execute on function public.move_user_department(
  uuid, uuid, integer, text
) to authenticated;

