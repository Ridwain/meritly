-- Compatibility version: a valid token is trusted, while the old deployed
-- invite route temporarily falls back to General. A later migration removes
-- the fallback after the new route is deployed.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  token_text text := new.raw_user_meta_data->>'meritly_provisioning_token';
  invite_token uuid;
  provision private.pending_user_provisioning%rowtype;
  provision_found boolean := false;
  general_department_id integer;
begin
  if token_text is not null
     and token_text ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$' then
    invite_token := token_text::uuid;

    select p.*
    into provision
    from private.pending_user_provisioning p
    where p.token = invite_token
      and p.normalized_email = lower(btrim(new.email))
      and p.expires_at > now()
    for update;

    provision_found := found;
  end if;

  if provision_found then
    insert into public.profiles (
      id,
      full_name,
      role_id,
      department_id
    ) values (
      new.id,
      provision.full_name,
      (select r.id from public.roles r where r.name = 'employee'),
      provision.department_id
    );

    delete from private.pending_user_provisioning
    where token = invite_token;
  else
    select d.id
    into general_department_id
    from public.departments d
    where d.name = 'General';

    insert into public.profiles (
      id,
      full_name,
      role_id,
      department_id
    ) values (
      new.id,
      coalesce(
        nullif(btrim(new.raw_user_meta_data->>'full_name'), ''),
        split_part(new.email, '@', 1)
      ),
      (select r.id from public.roles r where r.name = 'employee'),
      general_department_id
    );
  end if;

  return new;
end;
$$;

revoke execute on function public.handle_new_user()
  from anon, authenticated, public;

