create function public.admin_list_users()
returns table (
  id uuid,
  full_name text,
  role text,
  email text,
  deleted_at timestamptz,
  accepted boolean,
  department_id integer,
  department_name text
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  can_manage_all boolean := public.has_permission('user.manage_all');
begin
  if not (
    can_manage_all
    or public.has_permission('user.invite')
    or public.has_permission('user.promote')
    or public.has_permission('user.archive')
    or public.has_permission('stats.view_all')
  ) then
    raise exception 'not allowed to list users';
  end if;

  return query
    select
      p.id,
      p.full_name,
      r.name,
      u.email::text,
      p.deleted_at,
      (p.accepted_at is not null),
      d.id,
      d.name
    from public.profiles p
    join public.roles r on r.id = p.role_id
    join public.departments d on d.id = p.department_id
    join auth.users u on u.id = p.id
    where p.id <> auth.uid()
      and (
        can_manage_all
        or (
          r.assignable_work
          and private.can_access_user(p.id)
        )
      )
    order by p.created_at;
end;
$$;

revoke execute on function public.admin_list_users() from anon, public;
grant execute on function public.admin_list_users() to authenticated;

