create function public.guard_profile_department()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.department_id is not distinct from old.department_id then
    return new;
  end if;

  if auth.uid() is not null
     and not public.has_permission('user.manage_all') then
    raise exception 'only a global manager may change a department';
  end if;

  return new;
end;
$$;

