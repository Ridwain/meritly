create table private.pending_user_provisioning (
  token uuid primary key default gen_random_uuid(),
  normalized_email text not null,
  full_name text not null,
  department_id integer not null
    references public.departments(id) on delete restrict,
  created_by uuid not null
    references public.profiles(id) on delete restrict,
  expires_at timestamptz not null default (now() + interval '30 minutes'),
  created_at timestamptz not null default now(),
  constraint pending_user_email_check
    check (normalized_email = lower(btrim(normalized_email))),
  constraint pending_user_name_check
    check (char_length(btrim(full_name)) between 2 and 120)
);

create unique index pending_user_provisioning_email_idx
  on private.pending_user_provisioning (normalized_email);
create index pending_user_provisioning_expiry_idx
  on private.pending_user_provisioning (expires_at);

revoke all on table private.pending_user_provisioning
  from public, anon, authenticated;

create function public.prepare_user_invite(
  p_email text,
  p_full_name text,
  p_department_id integer,
  p_created_by uuid
)
returns uuid
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  clean_email text := lower(btrim(coalesce(p_email, '')));
  clean_name text := btrim(coalesce(p_full_name, ''));
  new_token uuid;
begin
  delete from private.pending_user_provisioning
  where expires_at <= now();

  if clean_email = '' or clean_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then
    raise exception 'invalid email';
  end if;
  if char_length(clean_name) not between 2 and 120 then
    raise exception 'full name must be between 2 and 120 characters';
  end if;
  if not exists (
    select 1 from public.departments d where d.id = p_department_id
  ) then
    raise exception 'department not found';
  end if;
  if not exists (
    select 1 from public.profiles p where p.id = p_created_by
  ) then
    raise exception 'invite actor not found';
  end if;

  insert into private.pending_user_provisioning (
    normalized_email,
    full_name,
    department_id,
    created_by
  ) values (
    clean_email,
    clean_name,
    p_department_id,
    p_created_by
  )
  on conflict (normalized_email) do update
  set
    full_name = excluded.full_name,
    department_id = excluded.department_id,
    created_by = excluded.created_by,
    token = gen_random_uuid(),
    expires_at = now() + interval '30 minutes',
    created_at = now()
  returning token into new_token;

  return new_token;
end;
$$;

