create function private.can_access_user(target_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles me
    join public.profiles target on target.id = target_user_id
    where me.id = (select auth.uid())
      and me.deleted_at is null
      and (
        (select public.has_permission('user.manage_all'))
        or me.department_id = target.department_id
      )
  );
$$;

grant usage on schema private to authenticated;
grant execute on function private.can_access_user(uuid) to authenticated;
revoke execute on function private.can_access_user(uuid)
  from public, anon;

